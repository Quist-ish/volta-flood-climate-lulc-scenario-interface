#!/usr/bin/env python3
"""Spatial-block meta-learning reproduction for the eight current experiments.
Run 01 and 02 first. This script can take several minutes because it performs
five-fold spatial CV, repeated permutation importance and 500 block bootstraps.
"""
from pathlib import Path
import numpy as np, pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.model_selection import GroupKFold
from sklearn.metrics import roc_auc_score
from sklearn.inspection import permutation_importance
ROOT=Path(__file__).resolve().parents[1]; OUT=ROOT/'generated_outputs'; OUT.mkdir(exist_ok=True)
df=pd.read_csv(ROOT/'data'/'analysis_ready'/'CAP500_FACTORIAL_PREDICTIONS.csv.gz')
CLIM=['PRCPTOT','Rx1day','R10mm','R20mm','SDII']; TOPO=['HAND_m','elevation_m','slope_deg','log_upstream_area']; LULC=['LULC_forest_fraction','LULC_shrub_savanna_grass_fraction','LULC_wetland_fraction','LULC_cropland_fraction','LULC_urban_fraction','LULC_barren_fraction']; KEY=['climate_model','scenario','period','cell_id']; K3=['scenario','period','cell_id']
# Direct-period cell table
pp=df.pivot_table(index=KEY,columns='state',values='prob_cap500'); pp['dC']=pp.C1L0-pp.C0L0; pp['dL']=pp.C0L1-pp.C0L0; pp['dI']=pp.C1L1-pp.C1L0-pp.C0L1+pp.C0L0; pp['comb']=pp.C1L1-pp.C0L0
a1=df[df.climate_model=='ACCESS-CM2']; c00=a1[a1.state=='C0L0'].set_index(K3); c01=a1[a1.state=='C0L1'].set_index(K3)
T=c00[['lon','lat','cell_area_km2']+TOPO+CLIM+LULC].copy(); T.columns=['lon','lat','area']+TOPO+[c+'_base' for c in CLIM]+['base_'+c.split('_')[1] for c in LULC]
for c in LULC: T['d_'+c.split('_')[1]]=c01[c]-c00[c]
c10m=df[df.state=='C1L0'].set_index(KEY)[CLIM]; c00m=df[df.state=='C0L0'].set_index(KEY)[CLIM]; dcl=(c10m-c00m).groupby(level=K3).median(); dcl.columns=['d_'+c for c in CLIM]
T=T.join(dcl).join(pp.groupby(K3)[['dC','dL','dI','comb']].median()).reset_index()
# Add estimated 2061 rows generated by script 02
p2061=OUT/'estimated_2061_cell_experiments.csv'
if not p2061.exists(): raise SystemExit('Run code/02_estimate_2061_harmonized.py first')
T=pd.concat([T,pd.read_csv(p2061)],ignore_index=True,sort=False)
for c in ['dC','dL','dI','comb']: T[c]=T[c].round(6)
T['tot']=(T.dC.abs()+T.dL.abs()+T.dI.abs()).round(6); T['w']=T.tot*T.area; T['regime']=np.where(T.tot<.01,'inactive',np.where((T.dL.abs()+T.dI.abs()).round(6)>=T.dC.abs(),'landscape','climate'))
T['block']=(np.floor((T.lon+6)/2)).astype(int).astype(str)+'_'+(np.floor((T.lat-5)/2)).astype(int).astype(str)
CTX=TOPO+[c+'_base' for c in CLIM]+['base_forest','base_shrub','base_wetland','base_cropland','base_urban','base_barren']; DL=['d_forest','d_shrub','d_wetland','d_cropland','d_urban','d_barren']; DCL=['d_'+c for c in CLIM]; FEATS=CTX+DL+DCL
rng=np.random.default_rng(0)
def model(): return HistGradientBoostingClassifier(max_iter=300,learning_rate=.05,max_leaf_nodes=15,min_samples_leaf=20,l2_regularization=1.0,random_state=0)
def task(mask,y,name):
    D=T[mask].reset_index(drop=True); yy=y[mask].astype(int).values; X=D[FEATS]; g=D.block.values; oof=np.zeros(len(yy)); imps=[]
    for tr,te in GroupKFold(5).split(X,yy,g):
        m=model().fit(X.iloc[tr],yy[tr]); oof[te]=m.predict_proba(X.iloc[te])[:,1]; pi=permutation_importance(m,X.iloc[te],yy[te],scoring='roc_auc',n_repeats=10,random_state=0); imps.append(pi.importances_mean)
    auc=roc_auc_score(yy,oof); blocks=np.unique(g); bs=[]
    for _ in range(500):
        sel=rng.choice(blocks,len(blocks),replace=True); idx=np.concatenate([np.where(g==b)[0] for b in sel]);
        if len(np.unique(yy[idx]))==2: bs.append(roc_auc_score(yy[idx],oof[idx]))
    lo,hi=np.percentile(bs,[2.5,97.5]); imp=pd.Series(np.mean(imps,axis=0),index=FEATS).sort_values(ascending=False)
    return {'target':name,'n':len(yy),'prevalence':yy.mean(),'roc_auc':auc,'ci_lo':lo,'ci_hi':hi,'top5':'; '.join(f'{k} ({v:.3f})' for k,v in imp.head(5).items())}
active=T.tot>=.01
rows=[task(pd.Series(True,index=T.index),active,'Active vs inactive cell'),task(active,T.regime=='landscape','Landscape- vs climate-dominated (active cells)'),task(T.comb.abs()>=.01,T.comb>0,'Positive vs negative combined response (|combined| >= 0.01)')]
pd.DataFrame(rows).to_csv(OUT/'spatial_meta_learning_reimplementation.csv',index=False)
print(pd.DataFrame(rows).to_string(index=False))
print('Compare with reference_outputs/current_reported/Supplement_Table_S19_spatial_meta_learning.csv; the original revision execution file was not supplied.')
